-- Schema for NoteStream. Column types match the JPA entities so `ddl-auto: validate` passes.
-- String fields without columnDefinition -> varchar(255); TEXT columns -> text; LocalDateTime -> timestamp(6).

CREATE TABLE courses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMP(6)
);

CREATE TABLE documents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename     VARCHAR(255) NOT NULL,
    content_type VARCHAR(255),
    file_size    BIGINT,
    uploaded_at  TIMESTAMP(6),
    course_id    BIGINT NOT NULL REFERENCES courses (id) ON DELETE CASCADE
);

CREATE TABLE chunks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content     TEXT NOT NULL,
    chunk_index INTEGER,
    start_page  INTEGER,
    end_page    INTEGER,
    embedding   VECTOR(1536),
    document_id BIGINT NOT NULL REFERENCES documents (id) ON DELETE CASCADE
);

CREATE TABLE questions (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text      TEXT NOT NULL,
    asked_at  TIMESTAMP(6),
    course_id BIGINT NOT NULL REFERENCES courses (id) ON DELETE CASCADE
);

CREATE TABLE answers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text         TEXT NOT NULL,
    generated_at TIMESTAMP(6),
    question_id  BIGINT NOT NULL UNIQUE REFERENCES questions (id) ON DELETE CASCADE
);

CREATE TABLE answer_citations (
    answer_id BIGINT NOT NULL REFERENCES answers (id) ON DELETE CASCADE,
    chunk_id  BIGINT NOT NULL REFERENCES chunks (id) ON DELETE CASCADE
);

-- Fetch documents/chunks/questions by their parent.
CREATE INDEX idx_documents_course_id ON documents (course_id);
CREATE INDEX idx_chunks_document_id ON chunks (document_id);
CREATE INDEX idx_questions_course_id ON questions (course_id);

-- Approximate nearest-neighbour index for cosine similarity (matches the <=> operator in findSimilarChunks).
CREATE INDEX idx_chunks_embedding ON chunks USING hnsw (embedding vector_cosine_ops);
